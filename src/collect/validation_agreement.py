"""Inter-rater agreement and precision of the defect links (see docs/VALIDATION_GUIDE.md).

Reads data/new/<id>/validation/rating_<Rater>.csv (two raters) and, if present, adjudicated.csv.
Writes results/defect_link_validation.csv (one row per target and question) and .md (summary + disagreements).

Usage: python src/collect/validation_agreement.py [--raters Dev,Dhruv]
"""
import argparse
import math
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from clone_repo import NEW, ROOT  # noqa: E402

QUESTIONS = ["q1_real_bug", "q2_commit_fixes_issue", "q3_files_part_of_fix"]
CODES = ("yes", "no", "unsure")


def norm(s: pd.Series) -> pd.Series:
    return s.fillna("").astype(str).str.strip().str.lower()


def cohen_kappa(a: pd.Series, b: pd.Series) -> float:
    n = len(a)
    if n == 0:
        return float("nan")
    po = (a == b).mean()
    pe = sum((a == c).mean() * (b == c).mean() for c in CODES)
    return float("nan") if pe == 1 else (po - pe) / (1 - pe)


def wilson(k: int, n: int, z: float = 1.96) -> tuple:
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (round(c - h, 3), round(c + h, 3))


def valid(df: pd.DataFrame) -> pd.Series:
    return pd.concat([norm(df[q]) == "yes" for q in QUESTIONS], axis=1).all(axis=1)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--raters", default="Dev,Dhruv")
    a = ap.parse_args()
    r1, r2 = a.raters.split(",")
    rows, md_dis, md_status = [], [], []
    for vdir in sorted(NEW.glob("*/validation")):
        tid = vdir.parent.name
        p1, p2 = vdir / f"rating_{r1}.csv", vdir / f"rating_{r2}.csv"
        if not (p1.exists() and p2.exists()):
            continue
        d1, d2 = pd.read_csv(p1, dtype=str).set_index("link_id"), pd.read_csv(p2, dtype=str).set_index("link_id")
        n = len(d1)
        done1 = int(pd.concat([norm(d1[q]).isin(CODES) for q in QUESTIONS], axis=1).all(axis=1).sum())
        done2 = int(pd.concat([norm(d2[q]).isin(CODES) for q in QUESTIONS], axis=1).all(axis=1).sum())
        md_status.append(f"| {tid} | {n} | {done1}/{n} | {done2}/{n} |")
        if done1 < n or done2 < n:
            continue
        final = d1[QUESTIONS].copy()
        for q in QUESTIONS:
            final[q] = norm(d1[q]).where(norm(d1[q]) == norm(d2[q]), "")
        adj = vdir / "adjudicated.csv"
        if adj.exists():
            ad = pd.read_csv(adj, dtype=str).set_index("link_id")
            for q in QUESTIONS:
                fill = norm(ad[q]).reindex(final.index).fillna("")
                final[q] = final[q].where(final[q] != "", fill)
        unresolved = int((final[QUESTIONS] == "").any(axis=1).sum())
        for q in QUESTIONS:
            x, y = norm(d1[q]), norm(d2[q].reindex(d1.index))
            rows.append(dict(target=tid, question=q, links=n, agreement=round((x == y).mean(), 3),
                             cohen_kappa=round(cohen_kappa(x, y), 3),
                             yes_rater1=int((x == "yes").sum()), yes_rater2=int((y == "yes").sum())))
            for lid in d1.index[x != y]:
                md_dis.append(f"| {lid} | {d1.loc[lid, 'issue']} | {q} | {x[lid]} | {y[lid]} | "
                              f"{final.loc[lid, q] or 'open'} |")
        v1, v2 = valid(d1), valid(d2.reindex(d1.index))
        vf = valid(final) if unresolved == 0 else None
        k = int(vf.sum()) if vf is not None else None
        rows.append(dict(target=tid, question="link valid (all yes)", links=n,
                         agreement=round((v1 == v2).mean(), 3),
                         cohen_kappa=round(cohen_kappa(v1.map({True: "yes", False: "no"}),
                                                       v2.map({True: "yes", False: "no"})), 3),
                         yes_rater1=int(v1.sum()), yes_rater2=int(v2.sum()),
                         precision_final=round(k / n, 3) if k is not None else None,
                         precision_ci95=str(wilson(k, n)) if k is not None else None,
                         unresolved_disagreements=unresolved))
    out = pd.DataFrame(rows)
    res = ROOT / "results"
    out.to_csv(res / "defect_link_validation.csv", index=False)
    md = ["# Manual validation of defect links", "",
          f"Two independent raters ({r1}, {r2}); protocol in docs/VALIDATION_GUIDE.md. Generated by "
          "`python src/collect/validation_agreement.py`.", "",
          "## Rating status", "", f"| Target | Links | {r1} | {r2} |", "|---|---:|---:|---:|", *md_status, ""]
    if len(out):
        md += ["## Agreement and precision", "",
               f"| Target | Question | Links | % agreement | Cohen's κ | yes ({r1}) | yes ({r2}) | final precision [95% CI] |",
               "|---|---|---:|---:|---:|---:|---:|---|"]
        for _, r in out.iterrows():
            prec = (f"{r.precision_final:.2f} {r.precision_ci95}" if "precision_final" in r and pd.notna(r.get("precision_final"))
                    else ("adjudication open" if r.question.startswith("link") else ""))
            md.append(f"| {r.target} | {r.question} | {r.links} | {r.agreement:.2f} | {r.cohen_kappa:.2f} | "
                      f"{r.yes_rater1} | {r.yes_rater2} | {prec} |")
        md += ["", "## Disagreements", "", f"| Link | Issue | Question | {r1} | {r2} | adjudicated |",
               "|---|---|---|---|---|---|", *(md_dis or ["| none | | | | | |"])]
    else:
        md += ["No target has two complete rating sheets yet."]
    (res / "defect_link_validation.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote results/defect_link_validation.{{csv,md}}; rating status:")
    print("\n".join(s.replace("|", " ") for s in md_status))


if __name__ == "__main__":
    main()
