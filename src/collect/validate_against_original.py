"""Validate our JTratch run + re-implemented aggregation against the authors' released file-level values.

Runs on target `hibernate-5.0-validation` (Hibernate ORM 5.0.0.Final, the paper's own release): after
`run_analyzers.py hibernate-5.0-validation`, compare every Catch_Based / Try_Based / Throws_Based metric
with external/scripts_with_input_data/input/File_Level-*.csv (Project == hibernate-5.0).

Usage: python src/collect/validate_against_original.py
Writes results/pipeline_validation_hibernate-5.0.csv and .md
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from aggregate_jtratch import aggregate  # noqa: E402
from clone_repo import NEW, ROOT, load_target  # noqa: E402
from history import release_files  # noqa: E402

TID, ORIG_PROJECT = "hibernate-5.0-validation", "hibernate-5.0"
INPUT = ROOT / "external" / "scripts_with_input_data" / "input"


def compare(ours: pd.DataFrame, theirs: pd.DataFrame, source: str) -> list:
    o, t = ours.set_index("File Path"), theirs.set_index("File Path")
    both = o.index.intersection(t.index)
    rows = [dict(source=source, metric="<file coverage>", files_original=len(t), files_ours=len(o),
                 files_both=len(both), exact_match_rate=np.nan, spearman=np.nan, mean_abs_diff=np.nan)]
    for col in t.columns:
        if col in ("Language", "Project") or col not in o.columns:
            if col not in ("Language", "Project"):
                rows.append(dict(source=source, metric=col, files_both=len(both), note="missing in ours"))
            continue
        a = pd.to_numeric(o.loc[both, col], errors="coerce")
        b = pd.to_numeric(t.loc[both, col], errors="coerce")
        ok = a.notna() & b.notna()
        rows.append(dict(source=source, metric=col, files_both=int(ok.sum()),
                         exact_match_rate=float((np.isclose(a[ok], b[ok], atol=1e-6)).mean()) if ok.any() else np.nan,
                         spearman=float(a[ok].corr(b[ok], method="spearman")) if ok.sum() > 2 else np.nan,
                         mean_abs_diff=float((a[ok] - b[ok]).abs().mean()) if ok.any() else np.nan,
                         mean_original=float(b[ok].mean()) if ok.any() else np.nan,
                         mean_ours=float(a[ok].mean()) if ok.any() else np.nan))
    return rows


def main() -> None:
    t = load_target(TID)
    wt = NEW / TID / "src"
    files = release_files(wt, t["include_regex"], t["exclude_regex"])
    C, T, TH = aggregate(NEW / TID / "raw" / "analyzer", wt, ORIG_PROJECT, keep_files=files)
    rows = []
    for ours, name in ((C, "Catch_Based"), (T, "Try_Based"), (TH, "Throws_Based")):
        theirs = pd.read_csv(INPUT / f"File_Level-{name}.csv")
        theirs = theirs[theirs.Project == ORIG_PROJECT]
        rows += compare(ours, theirs, name)
    v = pd.DataFrame(rows)
    out = ROOT / "results"
    v.to_csv(out / "pipeline_validation_hibernate-5.0.csv", index=False, float_format="%.4f")
    md = ["# Phase 1 pipeline validation: our JTratch run vs. the authors' released values (Hibernate 5.0.0.Final)", "",
          "Generated by `python src/collect/validate_against_original.py`. *Exact* = share of common files whose value",
          "matches to 1e-6; *Spearman* = rank correlation over common files.", "",
          "| Source | Metric | Files (orig / ours / both) | Exact | Spearman | Mean (orig → ours) |",
          "|---|---|---|---:|---:|---|"]
    for _, r in v.iterrows():
        if r.metric == "<file coverage>":
            md.append(f"| {r.source} | **file coverage** | {int(r.files_original)} / {int(r.files_ours)} / {int(r.files_both)} | | | |")
        elif isinstance(r.get("note"), str):
            md.append(f"| {r.source} | {r.metric} | — | — | — | {r.note} |")
        else:
            md.append(f"| {r.source} | {r.metric} | {int(r.files_both)} | {r.exact_match_rate:.2f} | "
                      f"{r.spearman:.2f} | {r.mean_original:.3f} → {r.mean_ours:.3f} |")
    (out / "pipeline_validation_hibernate-5.0.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(v[["source", "metric", "files_both", "exact_match_rate", "spearman"]].to_string())


if __name__ == "__main__":
    main()
