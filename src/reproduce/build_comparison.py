"""Build results/reproduction_comparison.{csv,md} from Phase 0 runs.

Reads:
  results/reproduce/{asis,fixed}/base_test_2.csv   (our runs of the authors' code)
  external/scripts_with_input_data/output/base_test_2_BKP.csv  (authors' own released output, if present)
  results/reproduce/asis/metric_groups.csv         (which column belongs to which metric group)
Writes:
  results/reproduction_comparison.csv / .md

Usage: python src/reproduce/build_comparison.py
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "results"

# Paper, Table 4 (optimism-reduced Nagelkerke R2 on simplified model) and construction indicators.
PAPER = {
    ("umbraco-7.6", "BASE"): dict(r2=0.09, budget=15, potential=12, cutoff=0.70),
    ("umbraco-7.6", "BSFC"): dict(r2=0.09, budget=15, potential=23, cutoff=0.24),
    ("umbraco-7.6", "BSAP"): dict(r2=0.18, budget=15, potential=16, cutoff=0.67),
    ("hadoop-2.6", "BASE"): dict(r2=0.33, budget=59, potential=10, cutoff=0.70),
    ("hadoop-2.6", "BSFC"): dict(r2=0.37, budget=59, potential=31, cutoff=0.70),
    ("hadoop-2.6", "BSAP"): dict(r2=0.35, budget=59, potential=23, cutoff=0.70),
    ("hibernate-5.0", "BASE"): dict(r2=0.21, budget=29, potential=18, cutoff=0.70),
    ("hibernate-5.0", "BSFC"): dict(r2=0.28, budget=29, potential=27, cutoff=0.70),
    ("hibernate-5.0", "BSAP"): dict(r2=0.23, budget=29, potential=19, cutoff=0.70),
}
PROJECT_LABEL = {"umbraco-7.6": "Umbraco", "hadoop-2.6": "Hadoop", "hibernate-5.0": "Hibernate"}
RUN_LABEL = {
    "authors_bkp": "Authors' released output (base_test_2_BKP.csv)",
    "asis": "Ours: authors' code as released",
    "fixed": "Ours: authors' code + BSFC bug fix",
}


def load_run(path: Path, run: str) -> pd.DataFrame:
    d = pd.read_csv(path)
    d = d[d["file_set"] == "CAT"].copy()  # presented results: files with catch blocks
    d["run"] = run
    return d


def eh_predictors(sig: str, base: set) -> str:
    if not isinstance(sig, str):
        return ""
    names = [s.strip() for s in sig.split(",")]
    return "; ".join(n for n in names if n and n != "TOTAL" and n not in base)


def main() -> None:
    groups = pd.read_csv(RES / "reproduce" / "asis" / "metric_groups.csv")
    base = set(groups.loc[groups.group == "base", "metric"])

    runs = []
    bkp = ROOT / "external" / "scripts_with_input_data" / "output" / "base_test_2_BKP.csv"
    if bkp.exists():
        runs.append(load_run(bkp, "authors_bkp"))
    for r in ("asis", "fixed"):
        p = RES / "reproduce" / r / "base_test_2.csv"
        if p.exists():
            runs.append(load_run(p, r))
    d = pd.concat(runs, ignore_index=True)

    rows = []
    for _, x in d.iterrows():
        key = (x["project"], x["metric_set"])
        paper = PAPER[key]
        rep = x["r2_c_r"]
        rows.append({
            "Project": PROJECT_LABEL[x["project"]],
            "Model": x["metric_set"],
            "Run": RUN_LABEL[x["run"]],
            "Original R2": paper["r2"],
            "Reproduced R2": round(rep, 3) if pd.notna(rep) else None,
            "Difference": round(rep - paper["r2"], 3) if pd.notna(rep) else None,
            "Significant EH predictors (ours)": eh_predictors(x["signifcant_r"], base),
            "Significant base predictors (ours)": "; ".join(
                s.strip() for s in str(x["signifcant_r"]).split(",") if s.strip() in base),
            "Apparent R2 (simplified, not corrected)": round(x["r2_r"], 3) if pd.notna(x["r2_r"]) else None,
            "Original budget": paper["budget"], "Our budget": x["budget"],
            "Original # potential predictors": paper["potential"], "Our # potential predictors": x["nvar_initial"],
            "Original cutoff": paper["cutoff"], "Our cutoff": x["cutoff"],
            "Files (n)": x["n"],
        })
    out = pd.DataFrame(rows)
    order = {"Umbraco": 0, "Hadoop": 1, "Hibernate": 2}
    morder = {"BASE": 0, "BSFC": 1, "BSAP": 2}
    rorder = {v: i for i, v in enumerate(RUN_LABEL.values())}
    out = out.sort_values(by=["Project", "Model", "Run"],
                          key=lambda s: s.map({**order, **morder, **rorder})).reset_index(drop=True)
    out.to_csv(RES / "reproduction_comparison.csv", index=False)

    md = ["# Reproduction comparison: paper Table 4 vs. our runs",
          "",
          "Optimism-reduced Nagelkerke R² of the **simplified** logistic models (files with ≥1 catch block),",
          "bootstrap B=1000 (`rms::validate`), seed 2018. *Difference* = Reproduced − Original.",
          "Generated by `python src/reproduce/build_comparison.py`; see docs/REPRODUCTION.md for how each run was made.",
          "",
          "## Main table", "",
          "| Project | Model | Run | Original R² | Reproduced R² | Difference | Significant EH predictors (ours) |",
          "|---|---|---|---:|---:|---:|---|"]
    for _, r in out.iterrows():
        md.append(f"| {r['Project']} | {r['Model']} | {r['Run']} | {r['Original R2']:.2f} | "
                  f"{r['Reproduced R2']:.3f} | {r['Difference']:+.3f} | {r['Significant EH predictors (ours)'] or '—'} |")
    md += ["", "## Model-construction indicators (paper Table 4, upper rows)", "",
           "| Project | Model | Run | Budget (paper / ours) | # potential predictors (paper / ours) | Cutoff (paper / ours) | Apparent R² |",
           "|---|---|---|---|---|---|---:|"]
    for _, r in out.iterrows():
        md.append(f"| {r['Project']} | {r['Model']} | {r['Run']} | {r['Original budget']} / {r['Our budget']} | "
                  f"{r['Original # potential predictors']} / {r['Our # potential predictors']} | "
                  f"{r['Original cutoff']:.2f} / {r['Our cutoff']:.3f} | {r['Apparent R2 (simplified, not corrected)']:.3f} |")
    new_rows = new_context(base)
    if new_rows is not None:
        new_rows.to_csv(RES / "new_context_comparison.csv", index=False)
        md += ["", "## New context (Phase 2): authors' pipeline (bug-fixed) on our newly collected data", "",
               "**Extension, not a faithful replication**: product metrics come from the open-source fallback "
               "(no Understand license), and the flow metrics come from JTratch without dependency jars or "
               "external Javadoc (see docs/DATA.md §3–4). Compared against the paper's value for the same project.", "",
               "| Context | Model | Paper (orig. release) R² | New release R² | Files (n) | Budget | # potential | "
               "Significant EH predictors | Significant base predictors |",
               "|---|---|---:|---:|---:|---:|---:|---|---|"]
        for _, r in new_rows.iterrows():
            paper_r2 = r["Paper R2 (original release)"]
            md.append(f"| {r['Context']} | {r['Model']} | {'—' if pd.isna(paper_r2) else f'{paper_r2:.2f}'} | "
                      f"{r['New R2']:.3f} | {r['Files (n)']} | {r['Budget']} | {r['# potential predictors']} | "
                      f"{r['Significant EH predictors'] or '—'} | {r['Significant base predictors'] or '—'} |")
    t5 = table5()
    if t5 is not None:
        md += ["", "## Paper Table 5: significant predictors, Wald χ² and effect (bug-fixed run)", "",
               "Effect = relative change of the predicted probability when the predictor is set to 110% of its mean",
               "(others at their means), as in the paper's MA4. A predictor 'missing' in our run is marked ✗.", "",
               "| ID | Project | Model | Predictor (ours) | Paper χ² | Our χ² | Paper effect | Our effect |",
               "|---|---|---|---|---:|---:|---:|---:|"]
        for _, r in t5.iterrows():
            ours_chi = f"{r.our_chi2:.2f}" if pd.notna(r.our_chi2) else "✗"
            ours_eff = f"{r.our_effect_pct:+.1f}%" if pd.notna(r.our_effect_pct) else "—"
            paper_eff = f"{r.paper_effect_pct:+.1f}%" if pd.notna(r.paper_effect_pct) else "—"
            md.append(f"| {r.id} | {PROJECT_LABEL[r.project]} | {r.model} | {r.predictor} | {r.paper_chi2:.2f} | "
                      f"{ours_chi} | {paper_eff} | {ours_eff} |")
        extra = extra_predictors(t5)
        md += ["", f"Predictors significant in our simplified models but not listed in Table 5: "
               f"{', '.join(extra) if extra else 'none'}."]
    (RES / "reproduction_comparison.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(out[["Project", "Model", "Run", "Original R2", "Reproduced R2", "Difference"]].to_string())


